import { APPLICANT_FIELDS } from "../utils/applicantFields.js";

function FieldControl({ field, value, onChange }) {
  const id = `applicant-${field.name}`;

  return (
    <div className="form-field">
      <label htmlFor={id}>{field.label}</label>
      {field.type === "select" ? (
        <select
          id={id}
          name={field.name}
          value={value}
          onChange={onChange}
          required
        >
          {field.options.map((option) => {
            const item =
              typeof option === "string"
                ? { value: option, label: option }
                : option;

            return (
              <option key={item.value} value={item.value}>
                {item.label}
              </option>
            );
          })}
        </select>
      ) : (
        <div className={`input-wrap ${field.prefix ? "has-prefix" : ""} ${field.suffix ? "has-suffix" : ""}`}>
          {field.prefix && <span className="input-affix prefix">{field.prefix}</span>}
          <input
            id={id}
            name={field.name}
            type="number"
            value={value}
            min={field.min}
            step={field.step}
            onChange={onChange}
            required
          />
          {field.suffix && <span className="input-affix suffix">{field.suffix}</span>}
        </div>
      )}
      {field.hint && <span className="field-hint">{field.hint}</span>}
    </div>
  );
}

export default function ApplicantForm({
  values,
  onChange,
  onSubmit,
  onReset,
  isSubmitting,
}) {
  return (
    <form className="applicant-form" onSubmit={onSubmit}>
      <div className="form-section">
        <div className="section-heading">
          <span className="section-number">01</span>
          <div>
            <h2>About the applicant</h2>
            <p>A few details about your household and work.</p>
          </div>
        </div>
        <div className="form-grid">
          {APPLICANT_FIELDS.slice(0, 5).map((field) => (
            <FieldControl
              key={field.name}
              field={field}
              value={values[field.name]}
              onChange={onChange}
            />
          ))}
        </div>
      </div>

      <div className="form-section financial-section">
        <div className="section-heading">
          <span className="section-number">02</span>
          <div>
            <h2>Loan &amp; finances</h2>
            <p>Use the same amounts and term as your application.</p>
          </div>
        </div>
        <div className="form-grid">
          {APPLICANT_FIELDS.slice(5).map((field) => (
            <FieldControl
              key={field.name}
              field={field}
              value={values[field.name]}
              onChange={onChange}
            />
          ))}
        </div>
      </div>

      <div className="form-actions">
        <button className="button button-primary" type="submit" disabled={isSubmitting}>
          {isSubmitting ? (
            <>
              <span className="spinner" aria-hidden="true" />
              Assessing application…
            </>
          ) : (
            <>
              Get my assessment <span aria-hidden="true">→</span>
            </>
          )}
        </button>
        <button
          className="button button-quiet"
          type="button"
          onClick={onReset}
          disabled={isSubmitting}
        >
          Reset form
        </button>
      </div>
      <p className="form-disclaimer">
        This estimate is generated by a machine-learning model and is not a
        lending decision.
      </p>
    </form>
  );
}
